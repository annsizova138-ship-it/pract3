"""Исключения приложения."""


class UvmError(Exception):
    """Базовая ошибка: её текст показывается пользователю."""


class ConfigError(UvmError):
    """Неверное значение параметра командной строки."""


class AsmError(UvmError):
    """Ошибка в тексте программы на языке ассемблера."""


class FileError(UvmError):
    """Файл невозможно прочитать или записать."""
